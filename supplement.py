"""Builds Supplementary_Material.docx directly from the analysis tables (no placeholders)."""
import json
import os

import pandas as pd
from docx import Document
from docx.enum.section import WD_ORIENT
from docx.shared import Pt, Cm

from config import CLASSES, STRATEGIES, MODELS
from models import DISPLAY_NAMES

def _fix_settings(doc):
    from docx.oxml.ns import qn as _qn
    z = doc.settings.element.find(_qn("w:zoom"))
    if z is not None and z.get(_qn("w:percent")) is None:
        z.set(_qn("w:percent"), "100")


SNAME = {"baseline": "Baseline", "cwl": "Class-weighted loss", "focal": "Focal loss", "oversample": "Oversampling",
         "dcgan": "DCGAN aug.", "diffusion": "Diffusion aug.", "sup50": "Supervised (50%)", "selftrain": "Self-training",
         "st_cwl": "Self-training + CWL", "fixmatch": "FixMatch", "random": "Random sampling", "al_lc": "AL: least conf.",
         "al_entropy": "AL: entropy", "al_bald": "AL: BALD", "al_coreset": "AL: core-set", "al_cwl": "AL: least conf. + CWL"}


def _table(doc, header, rows, size=7):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    for j, h in enumerate(header):
        c = t.rows[0].cells[j].paragraphs[0]
        r = c.add_run(str(h)); r.bold = True; r.font.size = Pt(size)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            r = t.rows[i + 1].cells[j].paragraphs[0].add_run(str(v)); r.font.size = Pt(size)
    doc.add_paragraph()


def _ms(g, col, pct=False):
    m, s = g[col].mean(), (g[col].std(ddof=1) if len(g) > 1 else 0.0)
    return f"{100 * m:.1f} ± {100 * s:.1f}" if pct else f"{m:.3f} ± {s:.3f}"


def write_supplement(out, df, edf, pcf, cdf, res_dir):
    doc = Document()
    st = doc.styles["Normal"]; st.font.name = "Times New Roman"; st.font.size = Pt(10)
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(1.8))
    doc.add_heading("Supplementary Material", 0)
    doc.add_paragraph("Leakage-controlled benchmark of data-centric strategies for imbalanced skin lesion classification. "
                      "All values are generated by analyze.py from the released code; mean ± SD over the five lesion-grouped folds "
                      "unless stated otherwise.")
    models = [m for m in MODELS if m in set(df.model)]
    strategies = [s for s in STRATEGIES if s in set(df.strategy)]

    doc.add_heading("Table S1. Internal (HAM10000) performance of every condition and architecture", 2)
    rows = []
    for m in models:
        for s in strategies:
            g = df[(df.model == m) & (df.strategy == s)]
            if len(g):
                rows.append([DISPLAY_NAMES[m], SNAME[s], _ms(g, "accuracy", True), _ms(g, "balanced_accuracy", True),
                             _ms(g, "macro_f1"), _ms(g, "mcc"), _ms(g, "auc"), _ms(g, "mel_auc"),
                             _ms(g, "mel_sens_at_spec80", True), _ms(g, "ece"), f"{g.train_minutes.mean():.1f}"])
    _table(doc, ["Model", "Condition", "Acc. (%)", "Bal. acc. (%)", "Macro-F1", "MCC", "Macro AUC", "Mel. AUC",
                 "Mel. sens. @ 80% spec. (%)", "ECE", "Train min/fold"], rows)

    doc.add_heading("Table S2. Per-class F1 (pooled out-of-fold predictions) for every architecture", 2)
    _table(doc, ["Model", "Condition"] + CLASSES,
           [[DISPLAY_NAMES[r.model], SNAME[r.strategy]] + [f"{getattr(r, c):.3f}" for c in CLASSES]
            for r in pcf.itertuples()])

    if cdf is not None and not cdf.empty:
        doc.add_heading("Table S3. All paired comparisons (Δ = condition − reference; Holm-adjusted within each family)", 2)
        _table(doc, ["Family", "Model", "Condition", "Reference", "ΔMacro-F1 [95% CI]", "p (bootstrap)", "ΔAccuracy [95% CI]",
                     "p (McNemar)"],
               [[r.family, DISPLAY_NAMES[r.model], SNAME[r.strategy], SNAME[r.reference],
                 f"{r.d_macro_f1:+.3f} [{r.f1_lo:+.3f}, {r.f1_hi:+.3f}]", f"{r.p_boot_holm:.3g}",
                 f"{r.d_acc:+.3f} [{r.acc_lo:+.3f}, {r.acc_hi:+.3f}]", f"{r.p_mcnemar_holm:.3g}"] for r in cdf.itertuples()])

    if edf is not None and not edf.empty:
        doc.add_heading("Table S4. External test performance for every architecture and condition", 2)
        rows = []
        for m in models:
            for s in strategies:
                e = edf[(edf.model == m) & (edf.strategy == s)]
                if e.empty:
                    continue
                i_ = e[e.dataset == "isic2019"]
                p_ = e[e.dataset == "ph2"]
                rows.append([DISPLAY_NAMES[m], SNAME[s],
                             _ms(i_, "macro_f1") if len(i_) else "–", _ms(i_, "balanced_accuracy", True) if len(i_) else "–",
                             _ms(i_, "mel_auc") if len(i_) else "–", _ms(p_, "mel_auc") if len(p_) else "–",
                             _ms(p_, "mel_sens_at_spec80", True) if len(p_) else "–"])
        _table(doc, ["Model", "Condition", "ISIC 2019 macro-F1", "ISIC 2019 bal. acc. (%)", "ISIC 2019 mel. AUC",
                     "PH2 mel. AUC", "PH2 mel. sens. @ 80% spec. (%)"], rows)

    sp = os.path.join(out, "sensitivity.csv")
    if os.path.exists(sp):
        s = pd.read_csv(sp)
        doc.add_heading("Table S5. Sensitivity analysis (macro-F1, mean ± SD over folds)", 2)
        g = s.groupby(["param", "value", "model", "strategy"]).macro_f1.agg(["mean", "std"]).reset_index()
        _table(doc, ["Parameter", "Value", "Model", "Condition", "Macro-F1"],
               [[r.param, r.value, DISPLAY_NAMES.get(r.model, r.model), SNAME.get(r.strategy, r.strategy),
                 f"{r['mean']:.3f} ± {0 if pd.isna(r['std']) else r['std']:.3f}"] for _, r in g.iterrows()])

    cp = os.path.join(res_dir, "config.json")
    if os.path.exists(cp):
        doc.add_heading("Table S6. Complete configuration used for the reported runs", 2)
        cfg = json.load(open(cp))
        _table(doc, ["Setting", "Value"], [[k, str(v)] for k, v in cfg.items()])

    for name, cap in (("learning_curves", "Figure S1. Training and validation curves under baseline training (first fold)."),
                      ("confusion", "Figure S2. Normalized confusion matrix of the best architecture under baseline training."),
                      ("reliability", "Figure S3. Reliability diagram of the best architecture under baseline training."),
                      ("effects_budget", "Figure S4. Change in macro-F1 for the label-budget comparisons.")):
        p = os.path.join(out, f"fig_{name}.png")
        if os.path.exists(p):
            doc.add_picture(p, width=Cm(20 if name == "learning_curves" else 12))
            doc.add_paragraph(cap)
    _fix_settings(doc)
    doc.save(os.path.join(out, "Supplementary_Material.docx"))
